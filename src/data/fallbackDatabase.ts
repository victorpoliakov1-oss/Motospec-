// ---------------------------------------------------------------------------
// Preset matching
// A preset is only used when the search clearly names that exact bike AND any
// year typed falls inside the generation the preset describes. Everything else
// goes to the live AI lookup, so a Softail never gets Road King parts and a
// "2019 KTM 390 Duke" never gets the 2024 (different engine) data.
// ---------------------------------------------------------------------------

interface PresetRule {
  key: string;
  match: RegExp[];      // at least one must match
  exclude?: RegExp[];   // none may match (different variants / generations)
  years: [number, number];
}

const PRESET_RULES: PresetRule[] = [
  { key: 'ducati panigale v4 s', match: [/panigale\s*v4/], exclude: [/\bv4\s*r\b/, /\bsp2?\b/, /\bv2\b/], years: [2022, 2024] },
  { key: 'yamaha mt-07', match: [/\bmt[\s-]?07\b/, /\bfz[\s-]?07\b/], exclude: [/tracer/, /y-?amt/], years: [2021, 2024] },
  { key: 'kawasaki ninja zx-6r', match: [/\bzx[\s-]?6r\b/, /ninja\s*636/], years: [2024, 2025] },
  { key: 'honda crf300l', match: [/\bcrf\s*300\s*l/], years: [2021, 2025] },
  { key: 'bmw r 1200 gs', match: [/\br\s*1200\s*gs\b/, /\bgs\s*1200\b/], exclude: [/adventure/, /\bgsa\b/], years: [2013, 2018] },
  { key: 'bmw r 1250 gs', match: [/\br\s*1250\s*gs\b/, /\bgs\s*1250\b/], exclude: [/adventure/, /\bgsa\b/], years: [2019, 2024] },
  { key: 'ktm 390 duke', match: [/\b390\s*duke\b/, /\bduke\s*390\b/], years: [2024, 2025] },
  { key: 'harley-davidson road king', match: [/road\s*king/, /\bflhr\b/], exclude: [/special/, /flhrxs/], years: [2014, 2016] },
];

function extractYears(norm: string): number[] {
  return (norm.match(/\b(19[5-9]\d|20\d{2})\b/g) || []).map(Number);
}

export function findPresetKey(modelName: string): string | null {
  const norm = modelName.toLowerCase().replace(/[()]/g, ' ').replace(/\s+/g, ' ').trim();
  const years = extractYears(norm);

  for (const rule of PRESET_RULES) {
    if (!rule.match.some((re) => re.test(norm))) continue;
    if (rule.exclude?.some((re) => re.test(norm))) continue;
    if (years.length > 0 && !years.some((y) => y >= rule.years[0] && y <= rule.years[1])) continue;
    return rule.key;
  }
  return null;
}

// Show the rider's own year in the title ("2016 ... Road King", not "2014"),
// and the generation the data covers in the year field ("2014–2016").
function presetDisplay(key: string, modelName: string): { model: string; year: string } {
  const rule = PRESET_RULES.find((r) => r.key === key)!;
  const baseName = (PRESET_SPECS[key]?.model || PRESET_PARTS[key]?.motorcycleModel || key)
    .replace(/\s*\([^)]*\d{4}[^)]*\)/g, '')
    .replace(/^\s*(19|20)\d{2}\s+/, '')
    .trim();
  const [from, to] = rule.years;
  const typedYear = extractYears(modelName.toLowerCase()).find((y) => y >= from && y <= to);
  return {
    model: typedYear ? `${typedYear} ${baseName}` : baseName,
    year: from === to ? String(from) : `${from}–${to}`,
  };
}

export function findMatchingPresetSpecs(modelName: string): MotorcycleSpecs | null {
  const key = findPresetKey(modelName);
  const matched = key ? PRESET_SPECS[key] : null;
  if (!key || !matched) return null;
  const display = presetDisplay(key, modelName);
  return {
    ...matched,
    ...display,
    sources: getGenuineTechnicalManualSources(display.model),
  };
}

export function findMatchingPresetParts(modelName: string): AftermarketPartsResponse | null {
  const key = findPresetKey(modelName);
  const baseParts = key ? PRESET_PARTS[key] : null;
  if (!key || !baseParts) return null;
  return { ...baseParts, motorcycleModel: presetDisplay(key, modelName).model };
}
